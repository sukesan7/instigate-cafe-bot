def test_pyproject_python_classifiers_align_with_ci_matrix() -> None:
    """Verify pyproject.toml requires-python, classifiers, uv.lock, Dockerfile, and CI matrix align on 3.11-3.13."""
    pyproject_text = (PROJECT_ROOT / "pyproject.toml").read_text(encoding="utf-8")
    pyproject = tomllib.loads(pyproject_text)
    project = pyproject["project"]

    # 1. requires-python must reject Python 3.10 and Python 3.14+ and accept 3.11-3.13
    req_py = str(project["requires-python"]).replace(" ", "")
    assert req_py == ">=3.11,<3.14", f"Expected requires-python '>=3.11,<3.14', got {req_py!r}"

    def _version_allowed(ver: tuple[int, int]) -> bool:
        m_ge = re.search(r">=(\d+)\.(\d+)", req_py)
        m_lt = re.search(r"<(\d+)\.(\d+)", req_py)
        assert m_ge is not None and m_lt is not None
        floor = (int(m_ge.group(1)), int(m_ge.group(2)))
        ceil = (int(m_lt.group(1)), int(m_lt.group(2)))
        return floor <= ver < ceil

    assert _version_allowed((3, 10)) is False, "Python 3.10 must be rejected by requires-python"
    assert _version_allowed((3, 11)) is True
    assert _version_allowed((3, 12)) is True
    assert _version_allowed((3, 13)) is True
    assert _version_allowed((3, 14)) is False, "Python 3.14 must be excluded by requires-python"

    # 2. Classifiers match exact supported set (3.11, 3.12, 3.13)
    classifiers = list(project["classifiers"])
    assert "Programming Language :: Python :: 3.10" not in classifiers
    assert "Programming Language :: Python :: 3.14" not in classifiers
    classifier_versions = {
        c.rsplit("::", 1)[-1].strip()
        for c in classifiers
        if c.startswith("Programming Language :: Python :: 3.")
    }
    assert classifier_versions == {"3.11", "3.12", "3.13"}

    # 3. GitHub Actions CI matrix matches declared supported versions exactly
    ci_yaml = yaml.safe_load((PROJECT_ROOT / ".github" / "workflows" / "ci.yml").read_text(encoding="utf-8"))
    ci_versions = set(ci_yaml["jobs"]["quality"]["strategy"]["matrix"]["python-version"])
    assert ci_versions == classifier_versions == {"3.11", "3.12", "3.13"}

    # 4. uv.lock requires-python matches pyproject.toml floor/ceiling (no stale >=3.10 lockfile)
    lock_header = "\n".join((PROJECT_ROOT / "uv.lock").read_text(encoding="utf-8").splitlines()[:15])
    m_lock = re.search(r'requires-python\s*=\s*"([^"]+)"', lock_header)
    assert m_lock is not None, "uv.lock missing requires-python header"
    assert m_lock.group(1).replace(" ", "") == ">=3.11,<3.14", (
        f"uv.lock requires-python {m_lock.group(1)!r} disagrees with pyproject.toml {req_py!r}"
    )

    # 5. Generated requirements exports match uv.lock with zero dead Python <3.11 markers
    req_txt = (PROJECT_ROOT / "requirements.txt").read_text(encoding="utf-8")
    req_lock = (PROJECT_ROOT / "requirements.lock").read_text(encoding="utf-8")
    assert "python_full_version < '3.11'" not in req_txt
    assert "python_full_version < '3.11'" not in req_lock

    # 6. Ruff target-version and mypy python_version stay within declared 3.11-3.13 bounds
    assert pyproject["tool"]["ruff"]["target-version"] == "py311"
    assert pyproject["tool"]["mypy"]["python_version"] in {"3.11", "3.12", "3.13"}

    # 7. Dockerfile base images use a supported Python version (3.12)
    dockerfile = (PROJECT_ROOT / "Dockerfile").read_text(encoding="utf-8")
    docker_py_versions = set(re.findall(r"FROM\s+python:(\d+\.\d+)-", dockerfile))
    assert docker_py_versions and docker_py_versions.issubset(classifier_versions)


