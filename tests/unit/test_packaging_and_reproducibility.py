"""Unit tests for Python packaging reproducibility, ignore rules, Docker hygiene, and verify_offline."""

from __future__ import annotations

import subprocess
from pathlib import Path

import pytest

from tools.verify_offline import check_python_version, check_requirements_generated

PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent

pytestmark = pytest.mark.unit


def test_requirements_exports_are_uv_autogenerated_without_hand_edited_drift() -> None:
    """Verify requirements.txt and requirements.lock are generated exports matching uv.lock."""
    res = check_requirements_generated(PROJECT_ROOT)
    assert res.ok, res.detail

    exported_txt = subprocess.check_output(
        ["uv", "export", "--frozen", "--no-dev", "--no-hashes", "--no-emit-project", "--quiet"],
        cwd=str(PROJECT_ROOT),
        text=True,
    )
    actual_txt = (PROJECT_ROOT / "requirements.txt").read_text(encoding="utf-8")
    # Compare package lines (ignoring the 2-line autogenerated comment header which includes -o filename)
    assert actual_txt.splitlines()[2:] == exported_txt.splitlines()[2:]


def test_pyproject_python_classifiers_align_with_ci_matrix() -> None:
    """Verify pyproject.toml advertises Python 3.11-3.13 (not untested 3.10 or unsupported 3.14)."""
    src = (PROJECT_ROOT / "pyproject.toml").read_text(encoding="utf-8")
    assert "Programming Language :: Python :: 3.10" not in src
    assert "Programming Language :: Python :: 3.14" not in src
    for ver in ("3.11", "3.12", "3.13"):
        assert f"Programming Language :: Python :: {ver}" in src


def test_gitignore_covers_secrets_sqlite_backups_lore_caches_ide_and_screenshot_work() -> None:
    """Verify git check-ignore excludes sensitive/local artifacts while permitting safe templates."""
    must_ignore = [
        ".env",
        ".env.local",
        ".env.production",
        "campus.db",
        "data/campus.db-wal",
        "data/campus.db-shm",
        "data/campus.sqlite-wal",
        "data/campus.db.bak.1700000000",
        "tools/lore.json",
        "tools/lore.tmu_files.json",
        "keys/server.pem",
        "id_ed25519",
        "bot.log",
        ".venv/bin/python",
        "__pycache__/foo.pyc",
        ".pytest_cache/v/cache",
        ".vscode/settings.json",
        ".idea/workspace.xml",
        "artifacts/benchmark_results.json",
        "status_issue_report.md",
        "assets/screenshots/raw/01.png",
        "assets/screenshots/01.unredacted.png",
        "dist/pkg.whl",
    ]
    for path in must_ignore:
        proc = subprocess.run(
            ["git", "check-ignore", "-q", path],
            cwd=str(PROJECT_ROOT),
            check=False,
        )
        assert proc.returncode == 0, (
            f"Expected .gitignore to ignore '{path}', but git check-ignore returned {proc.returncode}"
        )

    must_not_ignore = [
        ".env.example",
        "tools/lore.example.json",
        "tests/fixtures/synthetic_lore.json",
        "assets/ic_logo.png",
        "requirements.txt",
        "requirements.lock",
        "uv.lock",
    ]
    for path in must_not_ignore:
        proc = subprocess.run(
            ["git", "check-ignore", "-q", path],
            cwd=str(PROJECT_ROOT),
            check=False,
        )
        assert proc.returncode != 0, f"Safe tracked file '{path}' must NOT be ignored by .gitignore"


def test_dockerignore_and_dockerfile_copy_only_minimal_runtime_files() -> None:
    """Verify .dockerignore blocks secrets/docs/tests/screenshots and Dockerfile copies minimal runtime paths."""
    dockerignore = (PROJECT_ROOT / ".dockerignore").read_text(encoding="utf-8")
    for pattern in (
        ".env",
        "*.db-wal",
        "*.sqlite-wal",
        "*.db.bak.*",
        "*.pem",
        "*.key",
        "docs/",
        "tests/",
        "scripts/",
        "assets/screenshots/",
        "artifacts/",
    ):
        assert pattern in dockerignore, f".dockerignore missing pattern '{pattern}'"

    dockerfile = (PROJECT_ROOT / "Dockerfile").read_text(encoding="utf-8")
    assert "FROM python:3.12-slim-bookworm AS builder" in dockerfile
    assert "FROM python:3.12-slim-bookworm AS runtime" in dockerfile
    assert "COPY --chown=campusbot:campusbot assets/ic_logo.png /app/assets/ic_logo.png" in dockerfile
    assert "COPY . ." not in dockerfile, (
        "Dockerfile must never copy the entire repo blindly into image layers"
    )


def test_verify_offline_python_version_diagnostics() -> None:
    """Verify tools/verify_offline.py accepts 3.11-3.13 and gives actionable hints on 3.10 and 3.14."""
    assert check_python_version((3, 11, 9)).ok is True
    assert check_python_version((3, 12, 13)).ok is True
    assert check_python_version((3, 13, 2)).ok is True

    res_310 = check_python_version((3, 10, 14))
    assert res_310.ok is False
    assert "datetime.UTC" in res_310.detail
    assert "3.12" in res_310.remediation

    res_314 = check_python_version((3, 14, 10))
    assert res_314.ok is False
    assert "3.14" in res_314.detail
    assert "uv venv --python 3.12" in res_314.remediation
