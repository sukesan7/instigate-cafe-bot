"""No-network, no-live-token contributor verification runner with actionable diagnostics.

Runs all offline quality gates in deterministic order with cleared secrets and
disabled pollers, emitting clear remediation commands if any check fails:
1. Python interpreter support check (3.11-3.13; recommends managed Python 3.12 on 3.14 hosts)
2. Lockfile & generated requirements parity (`uv lock --check` + generated header check)
3. Secret & publish-safety scan (`tools/scan_secrets.py --enforce-clean`)
4. Offline AST & zero-token import smoke (`tools/smoke_offline.py`)
5. Documentation links & command-tree parity (`tools/check_docs.py`, `tools/check_command_docs.py`)
6. Ruff lint, Ruff format, and Mypy static type checks
7. Offline Pytest suite (optional `--fast` skips pytest for rapid static iteration)

Usage:
    uv run python tools/verify_offline.py [--fast]
"""

from __future__ import annotations

import argparse
import os
import subprocess
import sys
import time
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent

MIN_PYTHON = (3, 11)
MAX_PYTHON_EXCLUSIVE = (3, 14)

SAFE_OFFLINE_ENV_OVERRIDES: dict[str, str] = {
    "DISCORD_TOKEN": "",
    "GEMINI_API_KEY": "",
    "GO_API_KEY": "",
    "ODDS_API_KEY": "",
    "ALPHAVANTAGE_API_KEY": "",
    "TTC_MASTODON_ACCT": "",
    "LLM_ENABLED": "false",
    "MARKET_WATCH_ENABLED": "false",
    "MARKET_DAILY_REPORT_ENABLED": "false",
    "BTC_WATCH_ENABLED": "false",
    "JOBS_POLL_SECONDS": "0",
    "WORKDAY_POLL_SECONDS": "0",
    "JOBS_BOOTSTRAP_POST": "false",
    "TTC_BOOTSTRAP_POST_LATEST": "false",
    "ICBOT_ALLOW_GATEWAY": "false",
}


@dataclass(frozen=True)
class CheckResult:
    """Outcome of a single offline verification stage."""

    name: str
    ok: bool
    elapsed_s: float
    detail: str
    remediation: str = ""


def check_python_version(version_info: tuple[int, int, int] | None = None) -> CheckResult:
    """Verify the active interpreter falls within the supported 3.11-3.13 range."""
    t0 = time.monotonic()
    ver = version_info or (sys.version_info.major, sys.version_info.minor, sys.version_info.micro)
    ver_str = f"{ver[0]}.{ver[1]}.{ver[2]}"
    if ver[:2] < MIN_PYTHON:
        return CheckResult(
            name="Python interpreter",
            ok=False,
            elapsed_s=time.monotonic() - t0,
            detail=f"Detected Python {ver_str}; runtime requires >=3.11 (datetime.UTC).",
            remediation="Provision managed Python 3.12: `uv venv --python 3.12 && uv sync --frozen --dev`",
        )
    if ver[:2] >= MAX_PYTHON_EXCLUSIVE:
        return CheckResult(
            name="Python interpreter",
            ok=False,
            elapsed_s=time.monotonic() - t0,
            detail=(
                f"Detected Python {ver_str}; project supports 3.11–3.13 (<3.14) "
                "(e.g. Arch/Garuda host python3 may be 3.14)."
            ),
            remediation="Use a managed Python 3.12 virtualenv: `uv venv --python 3.12 && uv sync --frozen --dev`",
        )
    return CheckResult(
        name="Python interpreter",
        ok=True,
        elapsed_s=time.monotonic() - t0,
        detail=f"Python {ver_str} (within supported 3.11–3.13 matrix)",
    )


def check_requirements_generated(repo_root: Path = PROJECT_ROOT) -> CheckResult:
    """Verify requirements.txt and requirements.lock are uv-generated (not hand-edited drift)."""
    t0 = time.monotonic()
    missing_headers: list[str] = []
    for fname in ("requirements.txt", "requirements.lock"):
        fpath = repo_root / fname
        if not fpath.is_file():
            missing_headers.append(f"{fname} (missing)")
            continue
        first_line = fpath.read_text(encoding="utf-8").splitlines()[0] if fpath.stat().st_size else ""
        if "autogenerated by uv" not in first_line:
            missing_headers.append(f"{fname} (missing uv autogenerated header)")

    if missing_headers:
        return CheckResult(
            name="Generated requirements parity",
            ok=False,
            elapsed_s=time.monotonic() - t0,
            detail="Hand-edited or missing requirements export: " + ", ".join(missing_headers),
            remediation="Regenerate from uv.lock: `make export-requirements`",
        )
    return CheckResult(
        name="Generated requirements parity",
        ok=True,
        elapsed_s=time.monotonic() - t0,
        detail="requirements.txt and requirements.lock are uv-generated from uv.lock",
    )


def _run_stage(
    name: str,
    cmd: list[str],
    *,
    env: dict[str, str],
    remediation: str,
    repo_root: Path = PROJECT_ROOT,
) -> CheckResult:
    t0 = time.monotonic()
    try:
        proc = subprocess.run(
            cmd,
            cwd=str(repo_root),
            env=env,
            capture_output=True,
            text=True,
            check=False,
        )
    except OSError as exc:
        return CheckResult(
            name=name,
            ok=False,
            elapsed_s=time.monotonic() - t0,
            detail=f"Failed to execute {cmd[0]}: {exc}",
            remediation=remediation,
        )

    elapsed = time.monotonic() - t0
    if proc.returncode == 0:
        return CheckResult(name=name, ok=True, elapsed_s=elapsed, detail="passed")

    combined = (proc.stdout + "\n" + proc.stderr).strip()
    tail_lines = [line for line in combined.splitlines() if line.strip()][-6:]
    snippet = " | ".join(tail_lines) if tail_lines else f"exit code {proc.returncode}"
    return CheckResult(
        name=name,
        ok=False,
        elapsed_s=elapsed,
        detail=f"exit {proc.returncode}: {snippet[:360]}",
        remediation=remediation,
    )


def _offline_env() -> dict[str, str]:
    env = os.environ.copy()
    env.update(SAFE_OFFLINE_ENV_OVERRIDES)
    return env


def run_all_checks(*, fast: bool = False, repo_root: Path = PROJECT_ROOT) -> list[CheckResult]:
    """Run all offline verification stages and return ordered results."""
    py = sys.executable
    env = _offline_env()

    results: list[CheckResult] = [
        check_python_version(),
        check_requirements_generated(repo_root),
        _run_stage(
            "uv lock --check",
            ["uv", "lock", "--check"],
            env=env,
            remediation="Run `uv lock` (online) and `make export-requirements` after editing pyproject.toml.",
            repo_root=repo_root,
        ),
        _run_stage(
            "Secret & publish-safety scan",
            [py, "tools/scan_secrets.py", "--enforce-clean"],
            env=env,
            remediation="Untrack forbidden files (`git rm --cached <path>`) and inspect tools/scan_secrets.py output.",
            repo_root=repo_root,
        ),
        _run_stage(
            "Offline AST & import smoke",
            [py, "tools/smoke_offline.py"],
            env=env,
            remediation="Fix syntax or import-time side effects reported by `uv run python tools/smoke_offline.py`.",
            repo_root=repo_root,
        ),
        _run_stage(
            "Docs link & placeholder check",
            [py, "tools/check_docs.py"],
            env=env,
            remediation="Fix broken links, anchors, or placeholders reported by `uv run python tools/check_docs.py`.",
            repo_root=repo_root,
        ),
        _run_stage(
            "Command-tree docs parity",
            [py, "tools/check_command_docs.py"],
            env=env,
            remediation="Update docs/features.md or docs/configuration.md to match live /ic registrations.",
            repo_root=repo_root,
        ),
        _run_stage(
            "Ruff lint",
            [py, "-m", "ruff", "check", "."],
            env=env,
            remediation="Run `uv run ruff check --fix .` and inspect remaining lint findings.",
            repo_root=repo_root,
        ),
        _run_stage(
            "Ruff format check",
            [py, "-m", "ruff", "format", "--check", "."],
            env=env,
            remediation="Run `uv run ruff format .` to normalize formatting.",
            repo_root=repo_root,
        ),
        _run_stage(
            "Mypy static type check",
            [py, "-m", "mypy", "."],
            env=env,
            remediation="Fix type errors reported by `uv run mypy .`.",
            repo_root=repo_root,
        ),
    ]

    if not fast:
        results.append(
            _run_stage(
                "Offline pytest suite",
                [py, "-m", "pytest", "-q"],
                env=env,
                remediation="Run `uv run pytest -v --tb=short` to inspect failing offline tests.",
                repo_root=repo_root,
            )
        )

    return results


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Run no-network, no-live-token contributor verification with actionable diagnostics."
    )
    parser.add_argument(
        "--fast",
        action="store_true",
        help="Skip pytest and run static, lock, secret, smoke, docs, lint, and type checks only.",
    )
    args = parser.parse_args(list(argv) if argv is not None else None)

    results = run_all_checks(fast=args.fast)
    failures = [r for r in results if not r.ok]

    print("=" * 78)
    print(" Instigate Cafe Bot — Offline Contributor Verification Summary")
    print("=" * 78)
    for res in results:
        tag = "PASS" if res.ok else "FAIL"
        print(f" [{tag}] {res.name:<30} ({res.elapsed_s:5.2f}s)  {res.detail}")
        if not res.ok and res.remediation:
            print(f"        Fix: {res.remediation}")
    print("=" * 78)

    if failures:
        print(f"[FAIL] {len(failures)}/{len(results)} offline verification check(s) failed.")
        return 1

    print(f"[PASS] All {len(results)} offline verification checks passed (0 tokens, 0 live network).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
